import assert from 'node:assert/strict';
import test from 'node:test';
import { ProgressQueue } from '../app/account-client.ts';
import { createDefaultSave } from '../app/game-logic.ts';
const session = { account: { userId: 'test', username: 'Bober', isAdmin: false }, save: createDefaultSave(), revision: 3, savedAt: '', difficulty: 50 };
test('serializes saves and sends changes made while a request is pending', async () => {
  const requests = []; const resolvers = []; const persisted = [];
  const queue = new ProgressQueue(session, payload => { requests.push(payload); return new Promise(resolve => resolvers.push(resolve)); }, () => {}, (...args) => persisted.push(args));
  queue.update({ ...session.save, walletCoins: 10 });
  const first = queue.flush();
  assert.strictEqual(queue.flush(), first);
  queue.update({ ...session.save, walletCoins: 20 });
  resolvers.shift()({ revision: 4 });
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(requests.length, 2);
  assert.equal(requests[1].revision, 4);
  assert.equal(requests[1].save.walletCoins, 20);
  resolvers.shift()({ revision: 5 }); await first;
  assert.equal(queue.revision, 5);
  assert.equal(queue.dirty, false);
  assert.equal(persisted.at(-1)[2], false);
});
test('failed save retains local progress and can be retried without changing revision', async () => {
  let failing = true; const statuses = [];
  const queue = new ProgressQueue(session, async payload => { assert.equal(payload.revision, 3); if (failing) throw new Error('Offline'); return { revision: 4 }; }, status => statuses.push(status), () => {});
  queue.update({ ...session.save, walletCoins: 456 });
  await assert.rejects(queue.flush(), /Offline/);
  assert.equal(queue.dirty, true); assert.equal(queue.save.walletCoins, 456);
  failing = false; await queue.flush();
  assert.equal(queue.dirty, false); assert.equal(statuses.at(-1), 'saved');
});
